"""``_package_version()``: this checkout's own pyproject.toml must win over
installed distribution metadata, which goes stale the moment the version is
bumped without a reinstall (an editable install's egg-info is only
regenerated by ``pip install -e .``, not by editing pyproject.toml).

This is the exact bug a real run_provenance validation run surfaced: the
checkout's pyproject.toml said 0.9.1, but a stale tradingagents.egg-info on
sys.path (last regenerated when pyproject.toml said 0.5.1) made
``importlib.metadata.version("tradingagents")`` -- the function's old first
choice -- return 0.5.1 into result.json.

Single source of truth: both run_manifest (llm_trace.write_run_manifest) and
run_provenance (run_provenance.build_run_provenance) read this same
function, so they can never disagree (test 4).
"""

from __future__ import annotations

import json

import pytest

import tradingagents.llm_trace as llm_trace
from tradingagents.run_provenance import build_run_provenance


@pytest.mark.unit
def test_1_checkout_pyproject_wins_over_stale_installed_metadata(monkeypatch):
    def _stale_installed_metadata(name):
        assert name == "tradingagents"
        return "0.5.1"

    monkeypatch.setattr(
        "importlib.metadata.version", _stale_installed_metadata, raising=True
    )
    assert llm_trace._package_version() == "0.9.1"


@pytest.mark.unit
def test_2_falls_back_to_installed_metadata_outside_a_checkout(monkeypatch, tmp_path):
    # Simulate "no pyproject.toml alongside this module" by pointing at an
    # empty tmp_path instead of patching tomllib (which would affect every
    # other tomllib caller in the process).
    import pathlib

    fake_file = tmp_path / "tradingagents" / "llm_trace.py"
    fake_file.parent.mkdir()
    fake_file.write_text("")
    monkeypatch.setattr(llm_trace, "__file__", str(fake_file))
    monkeypatch.setattr(
        "importlib.metadata.version", lambda name: "1.2.3", raising=True
    )
    assert llm_trace._package_version() == "1.2.3"
    assert not (pathlib.Path(tmp_path) / "pyproject.toml").exists()


@pytest.mark.unit
def test_3_no_source_available_returns_none_not_a_fabricated_version(monkeypatch, tmp_path):
    fake_file = tmp_path / "tradingagents" / "llm_trace.py"
    fake_file.parent.mkdir()
    fake_file.write_text("")
    monkeypatch.setattr(llm_trace, "__file__", str(fake_file))

    def _raise(name):
        raise Exception("not installed")

    monkeypatch.setattr("importlib.metadata.version", _raise, raising=True)
    assert llm_trace._package_version() is None


@pytest.mark.unit
def test_4_run_provenance_and_run_manifest_use_the_identical_version(tmp_path):
    resolved = llm_trace._package_version()

    provenance = build_run_provenance(selected_analysts=["market"], config={"llm_provider": "ollama"})
    assert provenance["tradeproof_version"] == resolved

    llm_trace.write_run_manifest(
        tmp_path, ticker="NVDA", analysis_date="2026-09-30", depth=1,
        analysts=["market"], language="English", provider="ollama",
        effective_deep_model="A", effective_quick_model="B",
        config={"deep_think_llm": "A", "quick_think_llm": "B"},
        prompt_hashes={}, on_warn=lambda path, exc: None,
    )
    manifest = json.loads((tmp_path / "run_manifest.json").read_text())
    assert manifest["package_version"] == resolved
    assert resolved is not None  # this checkout always resolves a real version


@pytest.mark.unit
def test_5_implementation_never_hardcodes_the_current_version_string():
    import inspect

    source = inspect.getsource(llm_trace._package_version)
    assert "0.9.1" not in source


@pytest.mark.unit
def test_6_real_checkout_resolves_to_pyproject_tomls_own_version():
    from pathlib import Path

    import tomllib

    with open(Path(llm_trace.__file__).resolve().parent.parent / "pyproject.toml", "rb") as f:
        expected = tomllib.load(f)["project"]["version"]
    assert llm_trace._package_version() == expected
